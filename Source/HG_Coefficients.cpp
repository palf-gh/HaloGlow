/*
	HG_Coefficients.cpp

	Lookup of the offline-calibrated pyramid coefficients (spec §7.4). The table
	is immutable build data generated by tools/calibrate_v1.py from the impulse
	responses of this very core (tools/hg_impulse.cpp). It is sampled on a
	log2(R90) x Falloff grid; values in between are bilinear, and the result is
	renormalised so the spatial filter keeps DC gain 1.
*/

#include "HG_Core.h"

#include <algorithm>
#include <cmath>

namespace hg {
namespace {
#include "HG_CoefficientTable_v1.inc"
} // namespace

Coefficients LookupCoefficients(double log2Radius, double falloff)
{
	static_assert(kTableCoefficientCount == 2 * (1 + kMaxLevels) + kLocalBasisCount,
				  "coefficient table layout mismatch");
	if (!std::isfinite(log2Radius)) log2Radius = kTableLog2Min;
	if (!std::isfinite(falloff)) falloff = 50.0;

	const double sPos = (std::min(std::max(log2Radius, kTableLog2Min), kTableLog2Max) - kTableLog2Min)
		/ kTableLog2Step;
	const double fPos = std::min(std::max(falloff, 0.0), 100.0) / 100.0 * (kTableFalloffCount - 1);
	const int s0 = std::min(static_cast<int>(sPos), kTableRadiusCount - 2);
	const int f0 = std::min(static_cast<int>(fPos), kTableFalloffCount - 2);
	const double ts = sPos - s0;
	const double tf = fPos - f0;

	double v[kTableCoefficientCount];
	double sum = 0.0;
	for (int i = 0; i < kTableCoefficientCount; ++i) {
		const double c00 = kTable[f0][s0][i];
		const double c01 = kTable[f0][s0 + 1][i];
		const double c10 = kTable[f0 + 1][s0][i];
		const double c11 = kTable[f0 + 1][s0 + 1][i];
		const double c0 = c00 + (c01 - c00) * ts;
		const double c1 = c10 + (c11 - c10) * ts;
		v[i] = std::max(0.0, c0 + (c1 - c0) * tf);
		sum += v[i];
	}

	Coefficients c;
	if (!(sum > 0.0)) {
		c.a[0] = 1.0f;
		return c;
	}
	// Layout: a[0..L], c[0..L] (c[0] unused), b[0..H-1].
	for (int j = 0; j <= kMaxLevels; ++j) {
		c.a[j] = static_cast<float>(v[j] / sum);
		c.c[j] = j >= 1 ? static_cast<float>(v[1 + kMaxLevels + j] / sum) : 0.0f;
		if (j >= 1 && (c.a[j] > 0.0f || c.c[j] > 0.0f)) c.topLevel = j;
	}
	for (int h = 0; h < kLocalBasisCount; ++h)
		c.b[h] = static_cast<float>(v[2 * (1 + kMaxLevels) + h] / sum);
	return c;
}

} // namespace hg
