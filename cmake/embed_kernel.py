#!/usr/bin/env python3
"""Concatenate kernel sources into one byte array header.

Usage: embed_kernel.py -o out.h -n SYMBOL input1 [input2 ...]

Local #include lines of the concatenated headers are dropped, because the
headers themselves are already part of the output in order. A byte array (not a
string literal) avoids MSVC's string-literal length limits.
"""

import argparse
import re
from pathlib import Path

LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s+"(HG_PixelMath\.h|HG_Kernels\.h)"\s*$')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", required=True)
    ap.add_argument("-n", required=True)
    ap.add_argument("inputs", nargs="+")
    args = ap.parse_args()

    parts = []
    for path in args.inputs:
        text = Path(path).read_text(encoding="utf-8")
        lines = [l for l in text.splitlines() if not LOCAL_INCLUDE.match(l)]
        parts.append(f"// ---- {Path(path).name} ----\n" + "\n".join(lines) + "\n")
    data = "".join(parts).encode("utf-8")

    out = [f"// Generated by cmake/embed_kernel.py from: {', '.join(Path(p).name for p in args.inputs)}",
           "#pragma once", "#include <cstddef>",
           f"static const unsigned char {args.n}[] = {{"]
    for i in range(0, len(data), 20):
        out.append("  " + ", ".join(str(b) for b in data[i:i + 20]) + ",")
    out.append("  0 };")
    out.append(f"static const std::size_t {args.n}_size = {len(data)};")
    Path(args.o).write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
